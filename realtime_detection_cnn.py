# Run the live detection. Click "Start camera", then "Stop" to finish.
face = FaceLandmarks()

closed_since, alert_active, alerts = None, False, 0
label, overlay_url, alarm = "Click Start camera", "", False
t_prev, fps = time.time(), 0.0

while True:
    reply = eval_js('stream_frame("%s", "%s", %s)' % (
        label, overlay_url, "true" if alarm else "false"))
    if not reply:
        break

    frame = js_to_image(reply)          # not mirrored; the page mirrors the display
    h, w = frame.shape[:2]
    p_closed, boxes = predict_frame(frame, face, model, IMG_SIZE)
    now = time.time()
    fps = 0.9 * fps + 0.1 / max(now - t_prev, 1e-3)
    t_prev = now

    overlay = np.zeros((h, w, 4), np.uint8)   # transparent drawing layer
    alarm = False

    if p_closed is None:
        closed_since, alert_active = None, False
        status = "NO FACE DETECTED"
    else:
        is_closed = p_closed >= THRESHOLD
        box_color = (0, 0, 255, 255) if is_closed else (0, 255, 0, 255)
        for (x1, y1, x2, y2) in boxes:
            cv2.rectangle(overlay, (x1, y1), (x2, y2), box_color, 3)

        if is_closed:
            closed_since = closed_since or now
            dur = now - closed_since
            if dur >= SECONDS:
                if not alert_active:
                    alerts += 1
                    alert_active = True
                status = "DROWSINESS ALERT! WAKE UP!"
                alarm = True
                cv2.rectangle(overlay, (0, 0), (w - 1, h - 1), (0, 0, 255, 255), 14)
            else:
                status = "Eyes closed (%.1fs)" % dur
        else:
            closed_since, alert_active = None, False
            status = "Awake"

    pc = "%.2f" % p_closed if p_closed is not None else "--"
    label = "%s | P(closed): %s | Alerts: %d | %.1f fps" % (status, pc, alerts, fps)
    overlay_url = overlay_to_url(overlay)

# clean up the page and the camera
eval_js('stream_frame("", "", false)')
face.close()
print("Stopped. Total alerts:", alerts)