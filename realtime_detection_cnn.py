SECONDS = 1.5      # eyes closed this long => ALERT
THRESHOLD = 0.5    # P(closed) above this => eye closed

RIGHT_EYE = [33, 160, 158, 133, 153, 144, 246, 161, 159, 157, 154, 145, 7, 163]
LEFT_EYE = [362, 385, 387, 263, 373, 380, 466, 388, 386, 384, 381, 374, 249, 390]

