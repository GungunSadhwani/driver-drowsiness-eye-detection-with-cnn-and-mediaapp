def js_to_image(js_reply):
    b64 = js_reply.split(',')[1]
    arr = np.frombuffer(b64decode(b64), np.uint8)
    return cv2.imdecode(arr, cv2.IMREAD_COLOR)


def overlay_to_url(overlay_rgba):
    ok, png = cv2.imencode('.png', overlay_rgba)
    return 'data:image/png;base64,' + b64encode(png.tobytes()).decode()


