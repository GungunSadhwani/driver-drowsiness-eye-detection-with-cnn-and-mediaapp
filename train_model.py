"""
Train and evaluate a CNN that classifies eye images as OPEN or CLOSED.

Expected dataset layout (e.g. MRL Eye Dataset or the Kaggle "Drowsiness" eye datasets):

    data/
        closed/   img1.png, img2.png, ...
        open/     img1.png, img2.png, ...

Outputs (in --out-dir, default "outputs"):
    eye_state_cnn.keras        trained model (used by realtime_detection_cnn.py)
    metrics.json               accuracy, precision, recall, F1 on the TEST set
    classification_report.txt  per-class report
    confusion_matrix.png       confusion matrix plot
    training_curves.png        accuracy / loss curves

Positive class = CLOSED eyes (label 1), because missing a closed eye is the costly error.
So Recall = of all truly closed eyes, how many did we catch.

Usage:
    python train_model.py --data-dir data --epochs 15
"""

import argparse
import json
import os
import random
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import tensorflow as tf
from sklearn.metrics import (accuracy_score, classification_report,
                             confusion_matrix, f1_score, precision_score,
                             recall_score)
from sklearn.model_selection import train_test_split

IMG_EXTS = (".png", ".jpg", ".jpeg", ".bmp")
SEED = 42


def parse_args():
    p = argparse.ArgumentParser(description="Train eye open/closed CNN")
    p.add_argument("--data-dir", default="data")
    p.add_argument("--out-dir", default="outputs")
    p.add_argument("--img-size", type=int, default=64)
    p.add_argument("--batch-size", type=int, default=64)
    p.add_argument("--epochs", type=int, default=15)
    p.add_argument("--max-per-class", type=int, default=0,
                   help="Limit images per class (0 = use all). Handy for quick tests.")

    # If running inside a Jupyter/Colab notebook, ignore Jupyter's connection parameters.
    if any("kernel-" in arg for arg in sys.argv):
        return p.parse_known_args()[0]
    return p.parse_args()


def collect_files(data_dir, max_per_class):
    paths, labels = [], []
    for class_name, label in (("open", 0), ("closed", 1)):
        folder = os.path.join(data_dir, class_name)
        if not os.path.isdir(folder):
            raise SystemExit(f"Missing folder: {folder}\n"
                             f"Create '{data_dir}/open' and '{data_dir}/closed' with eye images.")
        files = []
        for root, _, names in os.walk(folder):
            files += [os.path.join(root, n) for n in names if n.lower().endswith(IMG_EXTS)]
        random.Random(SEED).shuffle(files)
        if max_per_class:
            files = files[:max_per_class]
        print(f"{class_name}: {len(files)} images")
        paths += files
        labels += [label] * len(files)
    return np.array(paths), np.array(labels)


def make_dataset(paths, labels, img_size, batch_size, training):
    def load(path, label):
        img = tf.io.read_file(path)
        img = tf.io.decode_image(img, channels=1, expand_animations=False)
        img = tf.image.resize(img, (img_size, img_size))
        img = tf.cast(img, tf.float32) / 255.0
        return img, tf.cast(label, tf.float32)

    ds = tf.data.Dataset.from_tensor_slices((paths, labels))
    if training:
        ds = ds.shuffle(len(paths), seed=SEED)
    ds = ds.map(load, num_parallel_calls=tf.data.AUTOTUNE)
    return ds.batch(batch_size).prefetch(tf.data.AUTOTUNE)


def build_model(img_size):
    augment = tf.keras.Sequential([
        tf.keras.layers.RandomRotation(0.08),
        tf.keras.layers.RandomZoom(0.1),
        tf.keras.layers.RandomContrast(0.2),
        tf.keras.layers.RandomTranslation(0.05, 0.05),
    ])
    model = tf.keras.Sequential([
        tf.keras.layers.Input((img_size, img_size, 1)),
        augment,
        tf.keras.layers.Conv2D(32, 3, activation="relu", padding="same"),
        tf.keras.layers.BatchNormalization(),
        tf.keras.layers.MaxPooling2D(),
        tf.keras.layers.Conv2D(64, 3, activation="relu", padding="same"),
        tf.keras.layers.BatchNormalization(),
        tf.keras.layers.MaxPooling2D(),
        tf.keras.layers.Conv2D(128, 3, activation="relu", padding="same"),
        tf.keras.layers.BatchNormalization(),
        tf.keras.layers.MaxPooling2D(),
        tf.keras.layers.GlobalAveragePooling2D(),
        tf.keras.layers.Dense(64, activation="relu"),
        tf.keras.layers.Dropout(0.4),
        tf.keras.layers.Dense(1, activation="sigmoid"),
    ])
    model.compile(optimizer=tf.keras.optimizers.Adam(1e-3),
                  loss="binary_crossentropy", metrics=["accuracy"])
    return model


def plot_curves(history, path):
    fig, ax = plt.subplots(1, 2, figsize=(11, 4))
    ax[0].plot(history.history["accuracy"], label="train")
    ax[0].plot(history.history["val_accuracy"], label="validation")
    ax[0].set_title("Accuracy"); ax[0].set_xlabel("Epoch"); ax[0].legend()
    ax[1].plot(history.history["loss"], label="train")
    ax[1].plot(history.history["val_loss"], label="validation")
    ax[1].set_title("Loss"); ax[1].set_xlabel("Epoch"); ax[1].legend()
    fig.tight_layout(); fig.savefig(path, dpi=150); plt.close(fig)


def plot_confusion(cm, path):
    fig, ax = plt.subplots(figsize=(4.5, 4))
    ax.imshow(cm, cmap="Blues")
    names = ["Open", "Closed"]
    ax.set_xticks([0, 1]); ax.set_xticklabels(names)
    ax.set_yticks([0, 1]); ax.set_yticklabels(names)
    ax.set_xlabel("Predicted"); ax.set_ylabel("Actual"); ax.set_title("Confusion Matrix")
    for i in range(2):
        for j in range(2):
            ax.text(j, i, str(cm[i, j]), ha="center", va="center",
                    color="white" if cm[i, j] > cm.max() / 2 else "black", fontsize=14)
    fig.tight_layout(); fig.savefig(path, dpi=150); plt.close(fig)


def main():
    args = parse_args()
    os.makedirs(args.out_dir, exist_ok=True)
    tf.keras.utils.set_random_seed(SEED)

    paths, labels = collect_files(args.data_dir, args.max_per_class)

    # 70% train / 15% validation / 15% test (stratified)
    p_train, p_tmp, y_train, y_tmp = train_test_split(
        paths, labels, test_size=0.30, stratify=labels, random_state=SEED)
    p_val, p_test, y_val, y_test = train_test_split(
        p_tmp, y_tmp, test_size=0.50, stratify=y_tmp, random_state=SEED)
    print(f"Train: {len(p_train)}  Val: {len(p_val)}  Test: {len(p_test)}")

    train_ds = make_dataset(p_train, y_train, args.img_size, args.batch_size, True)
    val_ds = make_dataset(p_val, y_val, args.img_size, args.batch_size, False)
    test_ds = make_dataset(p_test, y_test, args.img_size, args.batch_size, False)

    model = build_model(args.img_size)
    model.summary()

    model_path = os.path.join(args.out_dir, "eye_state_cnn.keras")
    callbacks = [
        tf.keras.callbacks.EarlyStopping(monitor="val_loss", patience=4,
                                         restore_best_weights=True),
        tf.keras.callbacks.ModelCheckpoint(model_path, monitor="val_loss",
                                           save_best_only=True),
        tf.keras.callbacks.ReduceLROnPlateau(monitor="val_loss", factor=0.5, patience=2),
    ]
    history = model.fit(train_ds, validation_data=val_ds,
                        epochs=args.epochs, callbacks=callbacks)

    # ---- Evaluation on the held-out TEST set ----
    probs = model.predict(test_ds).ravel()
    preds = (probs >= 0.5).astype(int)

    metrics = {
        "accuracy": float(accuracy_score(y_test, preds)),
        "precision": float(precision_score(y_test, preds)),
        "recall": float(recall_score(y_test, preds)),
        "f1_score": float(f1_score(y_test, preds)),
        "test_samples": int(len(y_test)),
    }
    cm = confusion_matrix(y_test, preds)
    report = classification_report(y_test, preds, target_names=["Open", "Closed"])

    print("\n=== TEST SET RESULTS (positive class = Closed) ===")
    for k, v in metrics.items():
        print(f"{k:>12}: {v:.4f}" if isinstance(v, float) else f" {k:>12}: {v}")
    print("\nConfusion matrix [rows=actual, cols=predicted] (Open, Closed):")
    print(cm)
    print("\n" + report)

    with open(os.path.join(args.out_dir, "metrics.json"), "w") as f:
        json.dump(metrics, f, indent=2)
    with open(os.path.join(args.out_dir, "classification_report.txt"), "w") as f:
        f.write(report)
    plot_confusion(cm, os.path.join(args.out_dir, "confusion_matrix.png"))
    plot_curves(history, os.path.join(args.out_dir, "training_curves.png"))
    model.save(model_path)
    print(f"\nSaved model and results to '{args.out_dir}/'")


if __name__ == "__main__":
    main()